export function getBlockName(tower) {
  if (tower === 1) return "Canopus";
  if (tower === 2) return "Orion";
  if (tower === 3) return "Nova";
  return "Tower";
}

export function getFlatInfo(tower, flatNumber) {
  const flatIndex = parseInt(flatNumber.slice(-2));

  let facing = (flatIndex === 1 || flatIndex === 2) ? "West Facing" : "East Facing";

  const sqftMap = {
    1: 3348,
    2: 2878,
    3: 3700
  };

  const bhkMap = {
    1: "4BHK",
    2: "3BHK",
    3: "4BHK"
  };

  return `${bhkMap[tower]} | ${sqftMap[tower]} Sq.ft | ${facing}`;
}

